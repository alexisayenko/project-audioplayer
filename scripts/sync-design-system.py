#!/usr/bin/env python3
"""Generate platform tokens from the Electrophone design system.

Source of truth: the "Electrophone" Design System artifact on claude.ai
(see docs/brand/README.md). Its project/tokens.json is committed as
docs/brand/tokens.json; this script turns that file into

  ios/Sources/DesignTokens.swift   (SwiftUI: colours per theme, type, spacing, radius)
  web/tokens.css                   (CSS custom properties, light + dark)

Never edit the generated files. Change the design system, re-export
tokens.json, run:  python3 scripts/sync-design-system.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "brand" / "tokens.json"
SWIFT_OUT = ROOT / "ios" / "Sources" / "DesignTokens.swift"
CSS_OUT = ROOT / "web" / "tokens.css"

HEADER = "GENERATED by scripts/sync-design-system.py from docs/brand/tokens.json — do not edit."


def camel(name: str) -> str:
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def hex_to_rgba(value: str) -> tuple[float, float, float, float]:
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    if len(v) == 6:
        v += "ff"
    if len(v) != 8:
        raise ValueError(f"not a hex colour: {value}")
    r, g, b, a = (int(v[i : i + 2], 16) / 255 for i in (0, 2, 4, 6))
    return r, g, b, a


def theme_values(token: dict, themes: list[str]) -> dict[str, str]:
    val = token["value"]
    if isinstance(val, str):
        return dict.fromkeys(themes, val)
    first = themes[0]
    return {t: val.get(t, val[first]) for t in themes}


def px(value) -> str:
    """'16px' -> '16', '0.5rem' -> '8', number -> str."""
    if isinstance(value, (int, float)):
        return str(value)
    m = re.fullmatch(r"([\d.]+)(px|rem|em)?", str(value))
    if not m:
        raise ValueError(f"not a length: {value}")
    n = float(m.group(1))
    if m.group(2) in ("rem", "em"):
        n *= 16
    return str(int(n)) if n.is_integer() else str(n)


def swift(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    out = [f"// {HEADER}", "", "import SwiftUI", "", "/// Electrophone design tokens. Colours adapt to light/dark automatically.", "enum DS {"]

    out.extend([
        "    // MARK: Colours",
        "    enum Color {",
    ])
    for tok in tokens["color"]["tokens"]:
        vals = theme_values(tok, themes)
        lr, lg, lb, la = hex_to_rgba(vals[light])
        dr, dg, db, da = hex_to_rgba(vals[dark])
        usage = tok.get("usage", "").replace("\n", " ")
        out.append(f"        /// {usage}")
        out.append(
            f"        static let {camel(tok['name'])} = SwiftUI.Color(light: ({lr:.3f}, {lg:.3f}, {lb:.3f}, {la:.3f}), dark: ({dr:.3f}, {dg:.3f}, {db:.3f}, {da:.3f}))"
        )
    out.extend([
        "    }",
        "",
    ])

    out.extend([
        "    // MARK: Type",
        "    enum Font {",
    ])
    families = tokens["type"].get("families", {})
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        design = ".monospaced" if "mono" in families.get(fam, fam).lower() else ".default"
        for st in group["styles"]:
            size = px(st["fontSize"])
            weight = st.get("fontWeight", 400)
            wname = {100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium", 600: "semibold", 700: "bold", 800: "heavy", 900: "black"}.get(int(weight), "regular")
            usage = st.get("usage", "").replace("\n", " ")
            out.extend([
                f"        /// {usage}",
                f"        static let {camel(st['name'])} = SwiftUI.Font.system(size: {size}, weight: .{wname}, design: {design})",
            ])
            if st.get("letterSpacing"):
                out.append(f"        static let {camel(st['name'])}Tracking: CGFloat = {px(st['letterSpacing'])}")
    out.extend([
        "    }",
        "",
    ])

    for family, enum_name in (("spacing", "Space"), ("radius", "Radius"), ("stroke", "Stroke")):
        fam = tokens.get(family)
        if not fam:
            continue
        out.extend([
            f"    // MARK: {enum_name}",
            f"    enum {enum_name} {{",
        ])
        for tok in fam["tokens"]:
            usage = tok.get("usage", "").replace("\n", " ")
            out.extend([
                f"        /// {usage}",
                f"        static let {camel(tok['name'])}: CGFloat = {px(tok['value'])}",
            ])
        out.extend([
            "    }",
            "",
        ])

    out.extend([
        "}",
        "",
        "extension SwiftUI.Color {",
        "    /// A colour with separate light and dark values, resolved by the system appearance.",
        "    init(light: (Double, Double, Double, Double), dark: (Double, Double, Double, Double)) {",
        "        self.init(uiColor: UIColor { trait in",
        "            let c = trait.userInterfaceStyle == .dark ? dark : light",
        "            return UIColor(red: c.0, green: c.1, blue: c.2, alpha: c.3)",
        "        })",
        "    }",
        "}",
    ])
    return "\n".join(out) + "\n"


def css_dark_overrides(tokens: dict, themes: list, light: str, dark: str) -> list:
    lines = ["@media (prefers-color-scheme: dark) {", "  :root {"]
    for tok in tokens["color"]["tokens"] + tokens.get("shadow", {}).get("tokens", []):
        v = theme_values(tok, themes)
        if v[dark] != v[light]:
            lines.append(f"    --{tok['name']}: {v[dark]};")
    lines.extend(["  }", "}"])
    return lines


def css_text_style(st: dict, fam: str) -> str:
    decl = [f"font-family: var(--font-{fam})", f"font-size: {st['fontSize']}", f"font-weight: {st.get('fontWeight', 400)}"]
    if st.get("lineHeight"):
        decl.append(f"line-height: {st['lineHeight']}")
    if st.get("letterSpacing"):
        decl.append(f"letter-spacing: {st['letterSpacing']}")
    return f".t-{st['name']} {{ {'; '.join(decl)}; }}"


def css(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    lines = [f"/* {HEADER} */", ":root {"]
    for tok in tokens["color"]["tokens"]:
        lines.append(f"  --{tok['name']}: {theme_values(tok, themes)[light]};")
    for key, stack in tokens["type"].get("families", {}).items():
        lines.append(f"  --font-{key}: {stack};")
    for family in ("spacing", "radius", "stroke"):
        for tok in tokens.get(family, {}).get("tokens", []):
            lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in tokens.get("shadow", {}).get("tokens", []):
        lines.append(f"  --{tok['name']}: {theme_values(tok, themes)[light]};")
    lines.append("}")
    if dark != light:
        lines.extend(css_dark_overrides(tokens, themes, light, dark))
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        lines.extend(css_text_style(st, fam) for st in group["styles"])
    return "\n".join(lines) + "\n"


def main() -> int:
    tokens = json.loads(SRC.read_text())
    SWIFT_OUT.write_text(swift(tokens))
    CSS_OUT.write_text(css(tokens))
    n = len(tokens["color"]["tokens"])
    print(f"wrote {SWIFT_OUT.relative_to(ROOT)} and {CSS_OUT.relative_to(ROOT)} ({n} colours, {sum(len(g['styles']) for g in tokens['type']['groups'])} text styles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
