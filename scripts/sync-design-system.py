#!/usr/bin/env python3
"""Generate platform tokens from the Electrophone design system.

Source of truth: the "Electrophone" Design System artifact on claude.ai
(see docs/brand/README.md). Its project/tokens.json is committed as
docs/brand/tokens.json; this script turns that file into

  ios/Sources/DesignTokens.swift   (SwiftUI: colours, chart colours, type plus Dynamic Type counterparts, spacing, radius, stroke,
                                    shadow, motion, icon, control, component, opacity)
  web/tokens.css                   (CSS custom properties, light + dark; tokens marked platform web are web only, platform ios are skipped)

All colour-valued tokens live in the color family (the artifact's parser accepts per-theme values and
{name} aliases only there). Inside it, chart-N tokens go to DS.Chart on iOS, tokens marked
"platform": "web" are skipped on iOS, and a "{name}" value resolves to var(--name) in CSS.
Shadow tokens reach iOS only when marked "platform": "ios" (one box-shadow layer: x y blur #rrggbbaa; the blur number is the
SwiftUI radius) and are then skipped in CSS. Motion durations become seconds, cubic-bezier curves become DSBezier.

Never edit the generated files. Change the design system, re-export
tokens.json, run:  python3 scripts/sync-design-system.py
Verify without writing:  python3 scripts/sync-design-system.py --check
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "brand" / "tokens.json"
SWIFT_OUT = ROOT / "ios" / "Sources" / "DesignTokens.swift"
CSS_OUT = ROOT / "web" / "tokens.css"

HEADER = "GENERATED by scripts/sync-design-system.py from docs/brand/tokens.json — do not edit."


def camel(name: str) -> str:
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def hex_to_rgba(value: str) -> tuple[float, float, float, float]:
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    if len(v) == 6:
        v += "ff"
    if len(v) != 8:
        raise ValueError(f"not a hex colour: {value}")
    r, g, b, a = (int(v[i : i + 2], 16) / 255 for i in (0, 2, 4, 6))
    return r, g, b, a


def theme_values(token: dict, themes: list[str]) -> dict[str, str]:
    val = token["value"]
    if isinstance(val, str):
        return dict.fromkeys(themes, val)
    first = themes[0]
    return {t: val.get(t, val[first]) for t in themes}


def css_values(token: dict, themes: list[str]) -> dict[str, str]:
    return {t: re.sub(r"\{([a-z0-9-]+)\}", r"var(--\1)", v) for t, v in theme_values(token, themes).items()}


def is_chart(token: dict) -> bool:
    return token["name"].startswith("chart-")


def on_ios(token: dict) -> bool:
    return token.get("platform", "ios") != "web"


def on_web(token: dict) -> bool:
    return token.get("platform", "web") != "ios"


def px(value) -> str:
    """'16px' -> '16', '0.5rem' -> '8', number -> str."""
    if isinstance(value, (int, float)):
        return str(value)
    m = re.fullmatch(r"([\d.]+)(px|rem|em)?", str(value))
    if not m:
        raise ValueError(f"not a length: {value}")
    n = float(m.group(1))
    if m.group(2) in ("rem", "em"):
        n *= 16
    return str(int(n)) if n.is_integer() else str(n)


FONT_WEIGHTS = {100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium", 600: "semibold", 700: "bold", 800: "heavy", 900: "black"}


def swift_colors(tokens: dict, themes: list[str]) -> list[str]:
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    out: list[str] = []
    color_tokens = [t for t in tokens["color"]["tokens"] if on_ios(t)]
    for mark, enum_name, group in (
        ("Colours", "Color", [t for t in color_tokens if not is_chart(t)]),
        ("Chart", "Chart", [t for t in color_tokens if is_chart(t)]),
    ):
        if not group:
            continue
        out.extend([
            f"    // MARK: {mark}",
            f"    enum {enum_name} {{",
        ])
        for tok in group:
            vals = theme_values(tok, themes)
            lr, lg, lb, la = hex_to_rgba(vals[light])
            dr, dg, db, da = hex_to_rgba(vals[dark])
            usage = tok.get("usage", "").replace("\n", " ")
            out.append(f"        /// {usage}")
            out.append(
                f"        static let {camel(tok['name'])} = SwiftUI.Color(light: ({lr:.3f}, {lg:.3f}, {lb:.3f}, {la:.3f}), dark: ({dr:.3f}, {dg:.3f}, {db:.3f}, {da:.3f}))"
            )
        out.extend([
            "    }",
            "",
        ])
    return out


def swift_fonts(tokens: dict) -> list[str]:
    out = [
        "    // MARK: Type",
        "    enum Font {",
    ]
    families = tokens["type"].get("families", {})
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        design = ".monospaced" if "mono" in families.get(fam, fam).lower() else ".default"
        for st in group["styles"]:
            size = px(st["fontSize"])
            wname = FONT_WEIGHTS.get(int(st.get("fontWeight", 400)), "regular")
            usage = st.get("usage", "").replace("\n", " ")
            out.extend([
                f"        /// {usage}",
                f"        static let {camel(st['name'])} = SwiftUI.Font.system(size: {size}, weight: .{wname}, design: {design})",
            ])
            if st.get("letterSpacing"):
                out.append(f"        static let {camel(st['name'])}Tracking: CGFloat = {px(st['letterSpacing'])}")
    out.extend([
        "    }",
        "",
    ])
    return out


TEXT_STYLES = {34: "largeTitle", 28: "title", 22: "title2", 20: "title3", 17: "body", 16: "callout", 15: "subheadline", 13: "footnote", 12: "caption", 11: "caption2"}


def text_style(st: dict) -> str:
    size = int(float(px(st["fontSize"])))
    if size == 17 and (st["name"] == "headline" or int(st.get("fontWeight", 400)) >= 600):
        return "headline"
    if size not in TEXT_STYLES:
        raise ValueError(f"no Dynamic Type text style for {st['name']} ({size}px)")
    return TEXT_STYLES[size]


def swift_dynamic_fonts(tokens: dict) -> list[str]:
    out = [
        "    // MARK: Dynamic Type",
        "    /// Scalable counterparts of DS.Font: the same roles and default sizes, tied to the Dynamic Type text style of the same size.",
        "    enum Dynamic {",
    ]
    families = tokens["type"].get("families", {})
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        design = ".monospaced" if "mono" in families.get(fam, fam).lower() else ".default"
        for st in group["styles"]:
            wname = FONT_WEIGHTS.get(int(st.get("fontWeight", 400)), "regular")
            out.append(f"        static let {camel(st['name'])} = SwiftUI.Font.system(.{text_style(st)}, design: {design}, weight: .{wname})")
    out.extend([
        "    }",
        "",
    ])
    return out


def swift_scales(tokens: dict) -> list[str]:
    out: list[str] = []
    for family, enum_name in (("spacing", "Space"), ("radius", "Radius"), ("stroke", "Stroke")):
        fam = tokens.get(family)
        if not fam:
            continue
        out.extend([
            f"    // MARK: {enum_name}",
            f"    enum {enum_name} {{",
        ])
        for tok in fam["tokens"]:
            usage = tok.get("usage", "").replace("\n", " ")
            out.extend([
                f"        /// {usage}",
                f"        static let {camel(tok['name'])}: CGFloat = {px(tok['value'])}",
            ])
        out.extend([
            "    }",
            "",
        ])
    return out


def parse_shadow_layer(value: str) -> tuple[float, float, float, str]:
    m = re.fullmatch(r"\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?\s+(#[0-9a-fA-F]{6,8})\s*", value)
    if not m:
        raise ValueError(f"iOS shadow must be a single layer 'x y blur #rrggbbaa': {value}")
    return float(m.group(1)), float(m.group(2)), float(m.group(3)), m.group(4)


def num(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else f"{value:.3f}".rstrip("0").rstrip(".")


def swift_shadows(tokens: dict, themes: list[str]) -> list[str]:
    toks = [t for t in tokens.get("shadow", {}).get("tokens", []) if t.get("platform") == "ios"]
    if not toks:
        return []
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    out = ["    // MARK: Shadow", "    enum Shadow {"]
    for tok in toks:
        vals = theme_values(tok, themes)
        x, y, blur, lc = parse_shadow_layer(vals[light])
        dx, dy, dblur, dc = parse_shadow_layer(vals[dark])
        if (x, y, blur) != (dx, dy, dblur):
            raise ValueError(f"{tok['name']}: geometry must match in both themes")
        lr, lg, lb, la = hex_to_rgba(lc)
        dr, dg, db, da = hex_to_rgba(dc)
        usage = tok.get("usage", "").replace("\n", " ")
        out.append(f"        /// {usage}")
        out.append(
            f"        static let {camel(tok['name'])} = DSShadow(color: SwiftUI.Color(light: ({lr:.3f}, {lg:.3f}, {lb:.3f}, {la:.3f}), dark: ({dr:.3f}, {dg:.3f}, {db:.3f}, {da:.3f})), tintOpacity: {la:.3f}, radius: {num(blur)}, x: {num(x)}, y: {num(y)})"
        )
    out.extend(["    }", ""])
    return out


def swift_value(tok: dict, family: str) -> tuple[str, str]:
    name, raw = tok["name"], str(tok["value"]).strip()
    if family == "icon" and name.startswith("icon-weight"):
        return "SwiftUI.Font.Weight", "." + FONT_WEIGHTS[int(raw)]
    if raw.endswith("ms"):
        return "Double", num(float(raw[:-2]) / 1000)
    m = re.fullmatch(r"cubic-bezier\(\s*([\d.\-]+)\s*,\s*([\d.\-]+)\s*,\s*([\d.\-]+)\s*,\s*([\d.\-]+)\s*\)", raw)
    if m:
        return "DSBezier", "DSBezier(" + ", ".join(num(float(g)) for g in m.groups()) + ")"
    return "CGFloat", num(float(px(raw)))


def swift_native_families(tokens: dict) -> list[str]:
    out: list[str] = []
    for family, enum_name in (("motion", "Motion"), ("icon", "Icon"), ("control", "Control"), ("component", "Component"), ("opacity", "Opacity")):
        fam = tokens.get(family)
        if not fam:
            continue
        out.extend([f"    // MARK: {enum_name}", f"    enum {enum_name} {{"])
        for tok in fam["tokens"]:
            if not on_ios(tok):
                continue
            typ, val = swift_value(tok, family)
            usage = tok.get("usage", "").replace("\n", " ")
            out.extend([f"        /// {usage}", f"        static let {camel(tok['name'])}: {typ} = {val}"])
        out.extend(["    }", ""])
    return out


def swift(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    out = [f"// {HEADER}", "", "import SwiftUI", "", "/// Electrophone design tokens. Colours adapt to light/dark automatically.", "enum DS {"]
    out.extend(swift_colors(tokens, themes))
    out.extend(swift_fonts(tokens))
    out.extend(swift_dynamic_fonts(tokens))
    out.extend(swift_scales(tokens))
    out.extend(swift_shadows(tokens, themes))
    out.extend(swift_native_families(tokens))

    out.extend([
        "}",
        "",
        "extension SwiftUI.Color {",
        "    /// A colour with separate light and dark values, resolved by the system appearance.",
        "    init(light: (Double, Double, Double, Double), dark: (Double, Double, Double, Double)) {",
        "#if canImport(UIKit)",
        "        self.init(uiColor: UIColor { trait in",
        "            let c = trait.userInterfaceStyle == .dark ? dark : light",
        "            return UIColor(red: c.0, green: c.1, blue: c.2, alpha: c.3)",
        "        })",
        "#else",
        "        self.init(nsColor: NSColor(name: nil) { appearance in",
        "            let isDark = appearance.bestMatch(from: [.aqua, .darkAqua]) == .darkAqua",
        "            let c = isDark ? dark : light",
        "            return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: c.3)",
        "        })",
        "#endif",
        "    }",
        "}",
        "",
        "/// One SwiftUI shadow level. `tintOpacity` is the alpha to apply when a call site supplies its own colour (see dsShadow in DSModifiers.swift).",
        "struct DSShadow {",
        "    let color: SwiftUI.Color",
        "    let tintOpacity: Double",
        "    let radius: CGFloat",
        "    let x: CGFloat",
        "    let y: CGFloat",
        "}",
        "",
        "/// A cubic-bezier easing curve (the x1 y1 x2 y2 of CSS cubic-bezier).",
        "struct DSBezier {",
        "    let x1: Double, y1: Double, x2: Double, y2: Double",
        "    init(_ x1: Double, _ y1: Double, _ x2: Double, _ y2: Double) { self.x1 = x1; self.y1 = y1; self.x2 = x2; self.y2 = y2 }",
        "}",
    ])
    return "\n".join(out) + "\n"


CSS_FAMILIES = ("spacing", "radius", "stroke", "shadow", "overlay", "state", "motion", "elevation", "icon", "control", "component", "opacity")


def css_tokens(tokens: dict) -> list:
    out = [t for t in tokens["color"]["tokens"] if on_web(t)]
    for family in CSS_FAMILIES:
        out.extend(t for t in tokens.get(family, {}).get("tokens", []) if on_web(t))
    return out


def css_dark_blocks(tokens: dict, themes: list, light: str, dark: str) -> list:
    # A var() reference resolves where it is declared, so tokens built on colour variables are
    # redeclared in the dark scope; otherwise a [data-theme="dark"] container would inherit day colours.
    decls = []
    for tok in css_tokens(tokens):
        v = css_values(tok, themes)
        if v[dark] != v[light] or "var(" in v[dark]:
            decls.append(f"--{tok['name']}: {v[dark]};")
    lines = ["@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {']
    lines.extend(f"    {d}" for d in decls)
    lines.extend(["  }", "}", '[data-theme="dark"] {'])
    lines.extend(f"  {d}" for d in decls)
    lines.append("}")
    return lines


def css_text_style(st: dict, fam: str) -> str:
    decl = [f"font-family: var(--font-{fam})", f"font-size: {st['fontSize']}", f"font-weight: {st.get('fontWeight', 400)}"]
    if st.get("lineHeight"):
        decl.append(f"line-height: {st['lineHeight']}")
    if st.get("letterSpacing"):
        decl.append(f"letter-spacing: {st['letterSpacing']}")
    if st.get("textTransform"):
        decl.append(f"text-transform: {st['textTransform']}")
    return f".t-{st['name']} {{ {'; '.join(decl)}; }}"


def css_font_shorthand(st: dict, fam: str) -> str:
    size = f"{st['fontSize']}/{st['lineHeight']}" if st.get("lineHeight") else st["fontSize"]
    return f"  --font-{st['name']}: {st.get('fontWeight', 400)} {size} var(--font-{fam});"


def css(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    lines = [f"/* {HEADER} */", ":root {"]
    for tok in tokens["color"]["tokens"]:
        if on_web(tok):
            lines.append(f"  --{tok['name']}: {css_values(tok, themes)[light]};")
    for key, stack in tokens["type"].get("families", {}).items():
        lines.append(f"  --font-{key}: {stack};")
    for family in CSS_FAMILIES:
        for tok in tokens.get(family, {}).get("tokens", []):
            if on_web(tok):
                lines.append(f"  --{tok['name']}: {css_values(tok, themes)[light]};")
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        lines.extend(css_font_shorthand(st, fam) for st in group["styles"])
    lines.append("}")
    if dark != light:
        lines.extend(css_dark_blocks(tokens, themes, light, dark))
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        lines.extend(css_text_style(st, fam) for st in group["styles"])
    return "\n".join(lines) + "\n"


def generate() -> tuple[dict[Path, str], dict]:
    with open(SRC, encoding="utf-8") as fh:
        tokens = json.load(fh)
    return {SWIFT_OUT: swift(tokens), CSS_OUT: css(tokens)}, tokens


def check(outputs: dict) -> int:
    stale = 0
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == text:
            continue
        stale += 1
        diff = list(difflib.unified_diff(current.splitlines(), text.splitlines(), f"{path.relative_to(ROOT)} (committed)", f"{path.relative_to(ROOT)} (generated)", lineterm="", n=0))
        added = sum(1 for d in diff if d.startswith("+") and not d.startswith("+++"))
        removed = sum(1 for d in diff if d.startswith("-") and not d.startswith("---"))
        print(f"STALE {path.relative_to(ROOT)}: generated output differs (+{added} -{removed} lines)")
        for line in diff[:40]:
            print(f"  {line}")
        if len(diff) > 40:
            print(f"  ... {len(diff) - 40} more diff lines")
    if stale:
        print("run: python3 scripts/sync-design-system.py")
        return 1
    print("ok: web/tokens.css and ios/Sources/DesignTokens.swift match docs/brand/tokens.json")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate web/tokens.css and ios/Sources/DesignTokens.swift from docs/brand/tokens.json.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if the generated files differ from what this script would write")
    args = parser.parse_args()
    outputs, tokens = generate()
    if args.check:
        return check(outputs)
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
    n = len(tokens["color"]["tokens"])
    print(f"wrote {SWIFT_OUT.relative_to(ROOT)} and {CSS_OUT.relative_to(ROOT)} ({n} colours, {sum(len(g['styles']) for g in tokens['type']['groups'])} text styles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
