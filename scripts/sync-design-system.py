#!/usr/bin/env python3
"""Generate platform tokens from the Electrophone design system.

Source of truth: the "Electrophone" Design System artifact on claude.ai
(see docs/brand/README.md). Its project/tokens.json is committed as
docs/brand/tokens.json; this script turns that file into

  ios/Sources/DesignTokens.swift   (SwiftUI: colours per theme, type, spacing, radius, shadows)
  web/tokens.css                   (CSS custom properties, light + dark)

Never edit the generated files. Change the design system, re-export
tokens.json, run:  python3 scripts/sync-design-system.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "brand" / "tokens.json"
SWIFT_OUT = ROOT / "ios" / "Sources" / "DesignTokens.swift"
CSS_OUT = ROOT / "web" / "tokens.css"

HEADER = "GENERATED by scripts/sync-design-system.py from docs/brand/tokens.json — do not edit."


def camel(name: str) -> str:
    parts = re.split(r"[-_.]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def hex_to_rgba(value: str) -> tuple[float, float, float, float]:
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    if len(v) == 6:
        v += "ff"
    if len(v) != 8:
        raise ValueError(f"not a hex colour: {value}")
    r, g, b, a = (int(v[i : i + 2], 16) / 255 for i in (0, 2, 4, 6))
    return r, g, b, a


def theme_values(token: dict, themes: list[str]) -> dict[str, str]:
    val = token["value"]
    if isinstance(val, str):
        return {t: val for t in themes}
    first = themes[0]
    return {t: val.get(t, val[first]) for t in themes}


def px(value) -> str:
    """'16px' -> '16', '0.5rem' -> '8', number -> str."""
    if isinstance(value, (int, float)):
        return str(value)
    m = re.fullmatch(r"([\d.]+)(px|rem|em)?", str(value))
    if not m:
        raise ValueError(f"not a length: {value}")
    n = float(m.group(1))
    if m.group(2) in ("rem", "em"):
        n *= 16
    return str(int(n)) if n.is_integer() else str(n)


def _split_layers(value: str) -> list[str]:
    """Split a box-shadow value on top-level commas (none of the layers use functions with commas)."""
    return [p.strip() for p in value.split(",") if p.strip()]


def parse_shadow(value: str) -> dict:
    """{'drop': (color, x, y, blur) | None, 'ring': (color, width) | None} from a box-shadow string (outer layers only)."""
    drop = ring = None
    for layer in _split_layers(value):
        parts = layer.split()
        if not parts or parts[0] == "inset" or parts[0] == "none":
            continue
        color = next((p for p in parts if p.startswith("#")), None)
        nums = [p for p in parts if not p.startswith("#")]
        if not color:
            continue
        x, y = float(px(nums[0])), float(px(nums[1]))
        blur = float(px(nums[2])) if len(nums) > 2 else 0.0
        spread = float(px(nums[3])) if len(nums) > 3 else 0.0
        if x == 0 and y == 0 and blur == 0 and spread > 0:
            ring = ring or (color, spread)
        else:
            drop = drop or (color, x, y, blur)
    return {"drop": drop, "ring": ring}


def swift_shadow(parsed: dict) -> str:
    def layer(color: str, x: float, y: float, blur: float) -> str:
        r, g, b, a = hex_to_rgba(color)
        return f"ShadowLayer(color: ({r:.3f}, {g:.3f}, {b:.3f}, {a:.3f}), x: {x:g}, y: {y:g}, blur: {blur:g})"

    d = parsed["drop"]
    rg = parsed["ring"]
    drop = layer(*d) if d else "nil"
    ring = layer(rg[0], 0, 0, rg[1]) if rg else "nil"
    return f"(drop: {drop}, ring: {ring})"


def swift(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    out = [f"// {HEADER}", "", "import SwiftUI", "", "/// Electrophone design tokens. Colours adapt to light/dark automatically.", "enum DS {"]

    out.append("    // MARK: Colours")
    out.append("    enum Color {")
    for tok in tokens["color"]["tokens"]:
        vals = theme_values(tok, themes)
        lr, lg, lb, la = hex_to_rgba(vals[light])
        dr, dg, db, da = hex_to_rgba(vals[dark])
        usage = tok.get("usage", "").replace("\n", " ")
        out.append(f"        /// {usage}")
        out.append(
            f"        static let {camel(tok['name'])} = SwiftUI.Color(light: ({lr:.3f}, {lg:.3f}, {lb:.3f}, {la:.3f}), dark: ({dr:.3f}, {dg:.3f}, {db:.3f}, {da:.3f}))"
        )
    out.append("    }")
    out.append("")

    out.append("    // MARK: Type")
    out.append("    enum Font {")
    families = tokens["type"].get("families", {})
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        design = ".monospaced" if "mono" in families.get(fam, fam).lower() else ".default"
        for st in group["styles"]:
            size = px(st["fontSize"])
            weight = st.get("fontWeight", 400)
            wname = {100: "ultraLight", 200: "thin", 300: "light", 400: "regular", 500: "medium", 600: "semibold", 700: "bold", 800: "heavy", 900: "black"}.get(int(weight), "regular")
            usage = st.get("usage", "").replace("\n", " ")
            out.append(f"        /// {usage}")
            out.append(f"        static let {camel(st['name'])} = SwiftUI.Font.system(size: {size}, weight: .{wname}, design: {design})")
            if st.get("letterSpacing"):
                out.append(f"        static let {camel(st['name'])}Tracking: CGFloat = {px(st['letterSpacing'])}")
    out.append("    }")
    out.append("")

    for family, enum_name in (("spacing", "Space"), ("radius", "Radius"), ("stroke", "Stroke")):
        fam = tokens.get(family)
        if not fam:
            continue
        out.append(f"    // MARK: {enum_name}")
        out.append(f"    enum {enum_name} {{")
        for tok in fam["tokens"]:
            usage = tok.get("usage", "").replace("\n", " ")
            out.append(f"        /// {usage}")
            out.append(f"        static let {camel(tok['name'])}: CGFloat = {px(tok['value'])}")
        out.append("    }")
        out.append("")

    shadows = tokens.get("shadow", {}).get("tokens", [])
    if shadows:
        out.append("    // MARK: Shadows (outer layers only; inset highlights are a web detail)")
        out.append("    enum Shadow {")
        for tok in shadows:
            vals = theme_values(tok, themes)
            lt, dk = parse_shadow(vals[light]), parse_shadow(vals[dark])
            usage = tok.get("usage", "").replace("\n", " ")
            out.append(f"        /// {usage}")
            out.append(
                f"        static let {camel(tok['name'])} = ShadowSpec(light: {swift_shadow(lt)}, dark: {swift_shadow(dk)})"
            )
        out.append("    }")
        out.append("")
    out.append("}")
    out.append("")
    out.append("/// One theme's outer shadow: the first drop layer plus an optional 1px ring layer (`0 0 0 1px <color>`).")
    out.append("struct ShadowLayer {")
    out.append("    let color: (Double, Double, Double, Double)")
    out.append("    let x: CGFloat, y: CGFloat, blur: CGFloat")
    out.append("}")
    out.append("")
    out.append("struct ShadowSpec {")
    out.append("    let light: (drop: ShadowLayer?, ring: ShadowLayer?)")
    out.append("    let dark: (drop: ShadowLayer?, ring: ShadowLayer?)")
    out.append("}")
    out.append("")
    out.append("extension View {")
    out.append("    /// Applies a token shadow: the drop layer as a SwiftUI shadow and the ring layer as a 1px stroke of `shape`.")
    out.append("    func dsShadow<S: InsettableShape>(_ spec: ShadowSpec, shape: S) -> some View {")
    out.append("        modifier(DSShadowModifier(spec: spec, shape: AnyInsettableShape(shape)))")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("struct DSShadowModifier: ViewModifier {")
    out.append("    let spec: ShadowSpec")
    out.append("    let shape: AnyInsettableShape")
    out.append("    @Environment(\\.colorScheme) private var scheme")
    out.append("    func body(content: Content) -> some View {")
    out.append("        let layers = scheme == .dark ? spec.dark : spec.light")
    out.append("        content")
    out.append("            .shadow(color: layers.drop.map { SwiftUI.Color(red: $0.color.0, green: $0.color.1, blue: $0.color.2, opacity: $0.color.3) } ?? .clear,")
    out.append("                    radius: (layers.drop?.blur ?? 0) / 2, x: layers.drop?.x ?? 0, y: layers.drop?.y ?? 0)")
    out.append("            .overlay(shape.strokeBorder(layers.ring.map { SwiftUI.Color(red: $0.color.0, green: $0.color.1, blue: $0.color.2, opacity: $0.color.3) } ?? .clear, lineWidth: layers.ring?.blur ?? 0))")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("struct AnyInsettableShape: InsettableShape {")
    out.append("    private let _path: (CGRect) -> Path")
    out.append("    private let _inset: (CGFloat) -> AnyInsettableShape")
    out.append("    init<S: InsettableShape>(_ shape: S) {")
    out.append("        _path = { shape.path(in: $0) }")
    out.append("        _inset = { AnyInsettableShape(shape.inset(by: $0)) }")
    out.append("    }")
    out.append("    func path(in rect: CGRect) -> Path { _path(rect) }")
    out.append("    func inset(by amount: CGFloat) -> AnyInsettableShape { _inset(amount) }")
    out.append("}")
    out.append("")
    out.append("extension SwiftUI.Color {")
    out.append("    /// A colour with separate light and dark values, resolved by the system appearance.")
    out.append("    init(light: (Double, Double, Double, Double), dark: (Double, Double, Double, Double)) {")
    out.append("        self.init(uiColor: UIColor { trait in")
    out.append("            let c = trait.userInterfaceStyle == .dark ? dark : light")
    out.append("            return UIColor(red: c.0, green: c.1, blue: c.2, alpha: c.3)")
    out.append("        })")
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"


def css(tokens: dict) -> str:
    themes = [t["id"] for t in tokens["color"]["themes"]]
    light, dark = themes[0], (themes[1] if len(themes) > 1 else themes[0])
    lines = [f"/* {HEADER} */", ":root {"]
    for tok in tokens["color"]["tokens"]:
        lines.append(f"  --{tok['name']}: {theme_values(tok, themes)[light]};")
    for key, stack in tokens["type"].get("families", {}).items():
        lines.append(f"  --font-{key}: {stack};")
    for family in ("spacing", "radius", "stroke"):
        for tok in tokens.get(family, {}).get("tokens", []):
            lines.append(f"  --{tok['name']}: {tok['value']};")
    for tok in tokens.get("shadow", {}).get("tokens", []):
        lines.append(f"  --{tok['name']}: {theme_values(tok, themes)[light]};")
    lines.append("}")
    if dark != light:
        lines.append("@media (prefers-color-scheme: dark) {")
        lines.append("  :root {")
        for tok in tokens["color"]["tokens"]:
            v = theme_values(tok, themes)
            if v[dark] != v[light]:
                lines.append(f"    --{tok['name']}: {v[dark]};")
        for tok in tokens.get("shadow", {}).get("tokens", []):
            v = theme_values(tok, themes)
            if v[dark] != v[light]:
                lines.append(f"    --{tok['name']}: {v[dark]};")
        lines.append("  }")
        lines.append("}")
    for group in tokens["type"].get("groups", []):
        fam = group.get("family", "sans")
        for st in group["styles"]:
            decl = [f"font-family: var(--font-{fam})", f"font-size: {st['fontSize']}", f"font-weight: {st.get('fontWeight', 400)}"]
            if st.get("lineHeight"):
                decl.append(f"line-height: {st['lineHeight']}")
            if st.get("letterSpacing"):
                decl.append(f"letter-spacing: {st['letterSpacing']}")
            lines.append(f".t-{st['name']} {{ {'; '.join(decl)}; }}")
    return "\n".join(lines) + "\n"


def main() -> int:
    tokens = json.loads(SRC.read_text())
    SWIFT_OUT.write_text(swift(tokens))
    CSS_OUT.write_text(css(tokens))
    n = len(tokens["color"]["tokens"])
    print(f"wrote {SWIFT_OUT.relative_to(ROOT)} and {CSS_OUT.relative_to(ROOT)} ({n} colours, {sum(len(g['styles']) for g in tokens['type']['groups'])} text styles)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
